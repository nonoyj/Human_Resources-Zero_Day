#!/usr/bin/env python3
"""
tools/art/publish_to_unity.py -- puts the real sprites where Unity can import them.

Unity only imports files under unity/Assets/, and it generates a .meta file for each one. The art is
authored in art/kit/ (where the generators and the twin renderer live), so this script publishes a
COPY into Unity and leaves a fingerprint so drift is detectable in one command:

    art/kit/unity_sprites.json        has sha256_16 per sprite
    unity/Assets/Art/Kit/.publish-manifest.json   records what was published, when, and the sha

USAGE
    python tools/art/publish_to_unity.py            # copy changed files, report what it did
    python tools/art/publish_to_unity.py --verify   # fail if the copy is stale (CI / self-check)
    python tools/art/publish_to_unity.py --prune    # also delete files in Unity that no longer exist

TWO MIRRORS, ON PURPOSE (and one of them was missing for a long time)
    unity/Assets/Art/Kit/...            authoring copy, byte-identical to art/kit, what the importer reads
    unity/Assets/Resources/Art/Kit/...  RUNTIME copy. DeskSceneBuilder and DeskBootstrap load through
                                        Resources.Load, and Resources.Load cannot see anything outside a
                                        Resources folder.

    The second one used to be produced only by the editor menu (HR//0D > Publish Art To Resources), so a
    fresh clone opened in Unity and pressed Play and got
        "sprite not found at Resources/Art/Kit/backgrounds/office_L0"
    even though the art was right there in the repository. That is a packaging bug, not an art bug: the
    file has to be COMMITTED, because Unity imports from the project folder and never runs python.
    publish_to_unity.py now writes both copies, so "press Play" works on a fresh clone.

Never touches .meta files, never edits the art, never deletes anything unless --prune is passed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
MANIFEST = os.path.join(ROOT, 'art', 'kit', 'unity_sprites.json')
DEST_ROOT = os.path.join(ROOT, 'unity', 'Assets')
PUBLISH_LOG = os.path.join(DEST_ROOT, 'Art', 'Kit', '.publish-manifest.json')
DATA_FILES = [
    (os.path.join(ROOT, 'art', 'kit', 'unity_sprites.json'),
     os.path.join(DEST_ROOT, 'Resources', 'unity_sprites.json')),
    # monitor font, the PAIR: Resources.Load<TextAsset>("fonts/monitor_font_5x7") for metrics and
    # Resources.Load<Texture2D>("fonts/monitor_font_5x7") for the glyph atlas. Copying only the json
    # left the CRT blank and the letter page without text.
    (os.path.join(ROOT, 'art', 'kit', 'fonts', 'monitor_font_5x7.json'),
     os.path.join(DEST_ROOT, 'Resources', 'fonts', 'monitor_font_5x7.json')),
    (os.path.join(ROOT, 'art', 'kit', 'fonts', 'monitor_font_5x7.png'),
     os.path.join(DEST_ROOT, 'Resources', 'fonts', 'monitor_font_5x7.png')),
    # palette for runtime tinting (MonitorScreenView reads Resources.Load<TextAsset>("palette"))
    (os.path.join(ROOT, 'art', 'kit', 'palette.json'),
     os.path.join(DEST_ROOT, 'Resources', 'palette.json')),
    (os.path.join(ROOT, 'unity', 'Assets', 'Content', 'desk_layout.json'),
     os.path.join(DEST_ROOT, 'Resources', 'desk_layout.json')),
]


def sha16(path: str) -> str:
    with open(path, 'rb') as fh:
        return hashlib.sha256(fh.read()).hexdigest()[:16]


def load_manifest() -> dict:
    with open(MANIFEST, 'r', encoding='utf-8') as fh:
        return json.load(fh)


RESOURCES_ROOT = os.path.join(DEST_ROOT, 'Resources')


def runtime_path(asset_path: str) -> str:
    """Assets/Art/Kit/applicants/x.png -> Assets/Resources/Art/Kit/applicants/x.png"""
    return os.path.join(RESOURCES_ROOT, asset_path[len('Assets/'):])


def plan(manifest: dict):
    """Returns (to_copy, up_to_date, missing_source). Each copy entry carries BOTH destinations:
    the authoring mirror under Assets/Art/Kit and the runtime mirror under Assets/Resources/Art/Kit."""
    to_copy, same, missing = [], [], []
    for sprite in manifest['sprites']:
        src = os.path.join(ROOT, sprite['source'])
        dst = os.path.join(DEST_ROOT, sprite['assetPath'][len('Assets/'):])
        rt = runtime_path(sprite['assetPath'])
        if not os.path.isfile(src):
            missing.append(sprite['source'])
            continue
        if (os.path.isfile(dst) and sha16(dst) == sprite['sha256_16']
                and os.path.isfile(rt) and sha16(rt) == sprite['sha256_16']):
            same.append(sprite['assetPath'])
        else:
            to_copy.append((src, dst, sprite, rt))
    return to_copy, same, missing


def write_log(published: dict) -> None:
    os.makedirs(os.path.dirname(PUBLISH_LOG), exist_ok=True)
    with open(PUBLISH_LOG, 'w', encoding='utf-8') as fh:
        json.dump({
            'note': 'generated by tools/art/publish_to_unity.py -- do not edit',
            'files': published,
        }, fh, indent=2, sort_keys=True)
        fh.write('\n')


def publish_content() -> list:
    """content/ -> unity/Assets/Resources/Content/ (v102).

    The intro script is written by the content team as JSON in content/intro/. Unity can only load
    Resources.Load<TextAsset>("Content/intro/intro_01"), which means the file has to exist under a
    Resources folder inside the Unity project. Same rule as the art mirror: committed, byte-identical,
    and verifiable -- a fresh clone must not depend on anyone running python.
    """
    src_root = os.path.join(ROOT, 'content')
    dst_root = os.path.join(ROOT, 'unity', 'Assets', 'Resources', 'Content')
    changed = []
    if not os.path.isdir(src_root):
        return changed
    for dirpath, _dirnames, filenames in os.walk(src_root):
        for name in sorted(filenames):
            if not name.lower().endswith('.json'):
                continue
            src = os.path.join(dirpath, name)
            rel = os.path.relpath(src, src_root)
            dst = os.path.join(dst_root, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            src_bytes = open(src, 'rb').read()
            if os.path.exists(dst) and open(dst, 'rb').read() == src_bytes:
                continue
            with open(dst, 'wb') as fh:
                fh.write(src_bytes)
            changed.append(os.path.relpath(dst, ROOT))
    return changed


def content_drift() -> list:
    """Files under content/ that are missing or different in the Unity Resources mirror."""
    src_root = os.path.join(ROOT, 'content')
    dst_root = os.path.join(ROOT, 'unity', 'Assets', 'Resources', 'Content')
    drift = []
    if not os.path.isdir(src_root):
        return drift
    for dirpath, _dirnames, filenames in os.walk(src_root):
        for name in sorted(filenames):
            if not name.lower().endswith('.json'):
                continue
            src = os.path.join(dirpath, name)
            dst = os.path.join(dst_root, os.path.relpath(src, src_root))
            if not os.path.isfile(dst) or sha16(dst) != sha16(src):
                drift.append(os.path.relpath(dst, ROOT))
    return drift


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--verify', action='store_true')
    ap.add_argument('--prune', action='store_true')
    args = ap.parse_args()

    if not os.path.isfile(MANIFEST):
        print('FAIL: art/kit/unity_sprites.json missing -- run tools/art/make_sprite_manifest.py')
        return 1
    manifest = load_manifest()
    to_copy, same, missing = plan(manifest)

    if missing:
        for m in missing:
            print('  FAIL source missing:', m)
        return 1

    if args.verify:
        if to_copy:
            for entry in to_copy[:10]:
                sprite = entry[2]
                here = os.path.isfile(entry[1]) and sha16(entry[1]) == sprite['sha256_16']
                there = os.path.isfile(entry[3]) and sha16(entry[3]) == sprite['sha256_16']
                missing_from = ('Assets/Art/Kit and Assets/Resources/Art/Kit' if not here and not there
                                else 'Assets/Art/Kit' if not here else 'Assets/Resources/Art/Kit')
                print('  MISSING OR STALE in %s:' % missing_from, sprite['assetPath'])
            print(f'FAIL: {len(to_copy)} sprite(s) out of date in unity/Assets/Art/Kit '
                  f'-- run: python tools/art/publish_to_unity.py')
            return 1
        stale_data = [os.path.relpath(dst, ROOT) for src, dst in DATA_FILES
                      if not os.path.isfile(dst) or sha16(dst) != sha16(src)]
        if stale_data:
            for d in stale_data:
                print('  STALE data file:', d)
            print('FAIL: Resources json out of date -- run: python tools/art/publish_to_unity.py')
            return 1
        content_stale = content_drift()
        if content_stale:
            for c in content_stale:
                print('  STALE content file:', c)
            print('FAIL: unity/Assets/Resources/Content is out of date -- run: '
                  'python tools/art/publish_to_unity.py')
            return 1
        for step in ('extract_frames.py', 'write_unity_metas.py'):
            script = os.path.join(os.path.dirname(os.path.abspath(__file__)), step)
            result = subprocess.run([sys.executable, script, '--check'], capture_output=True, text=True)
            if result.returncode != 0:
                print((result.stdout or result.stderr or '').strip())
                return 1
        print(f'PASS: unity/Assets/Art/Kit matches art/kit ({len(same)} sprites, sha256 verified)')
        print(f'      data files current: ' + ', '.join(os.path.basename(d) for _s, d in DATA_FILES))
        return 0

    for src, dst in DATA_FILES:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.isfile(dst) or sha16(dst) != sha16(src):
            shutil.copyfile(src, dst)
            print('  copied ' + os.path.relpath(dst, ROOT))

    for rel in publish_content():
        print('  copied ' + rel)

    published = {}
    for src, dst, sprite, rt in to_copy:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        os.makedirs(os.path.dirname(rt), exist_ok=True)
        if not os.path.isfile(rt) or sha16(rt) != sprite['sha256_16']:
            shutil.copyfile(src, rt)
        published[sprite['assetPath']] = sprite['sha256_16']
        print(f'  copied {sprite["assetPath"]}')
    # the log describes the whole published set, so a fresh clone verifies identically
    full = {s['assetPath']: s['sha256_16'] for s in manifest['sprites']}
    write_log(full)

    if args.prune:
        keep = {os.path.normpath(os.path.join(DEST_ROOT, a[len('Assets/'):]))
                for a in full}
        keep_rt = {os.path.normpath(runtime_path(a)) for a in full}
        for folder in ('applicants', 'portraits', 'ui', 'icons', 'stamps', 'desk', 'backgrounds', 'sweep'):
            d = os.path.join(DEST_ROOT, 'Art', 'Kit', folder)
            if not os.path.isdir(d):
                continue
            for f in os.listdir(d):
                if f.endswith('.png') and os.path.normpath(os.path.join(d, f)) not in keep:
                    os.remove(os.path.join(d, f))
                    print('  pruned', os.path.relpath(os.path.join(d, f), ROOT))

    # The frames and the .meta files are as much a build input as the PNGs are (BUG-045, BUG-046): the game
    # loads frames/<stem>__<frame>.png through Resources, and Unity only imports a PNG as a Sprite if the
    # .meta says so. Both are generated here so nobody has to remember them.
    for step in ('extract_frames.py', 'write_unity_metas.py'):
        script = os.path.join(os.path.dirname(os.path.abspath(__file__)), step)
        result = subprocess.run([sys.executable, script], capture_output=True, text=True)
        tail = (result.stdout or result.stderr or '').strip().splitlines()
        print('  %s: %s' % (step, tail[-1] if tail else 'ok'))
        if result.returncode != 0:
            print('  FAIL %s' % step)
            return 1

    print(f'published: {len(to_copy)} copied, {len(same)} already current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
