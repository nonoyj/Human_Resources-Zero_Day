#!/usr/bin/env python3
"""
tools/art/publish_to_unity.py -- puts the real sprites where Unity can import them.

Unity only imports files under unity/Assets/, and it generates a .meta file for each one. The art is
authored in art/kit/ (where the generators and the twin renderer live), so this script publishes a
COPY into Unity and leaves a fingerprint so drift is detectable in one command:

    art/kit/unity_sprites.json        has sha256_16 per sprite
    unity/Assets/Art/Kit/.publish-manifest.json   records what was published, when, and the sha

USAGE
    python tools/art/publish_to_unity.py            # copy changed files, report what it did
    python tools/art/publish_to_unity.py --verify   # fail if the copy is stale (CI / self-check)
    python tools/art/publish_to_unity.py --prune    # also delete files in Unity that no longer exist

Never touches .meta files, never edits the art, never deletes anything unless --prune is passed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
MANIFEST = os.path.join(ROOT, 'art', 'kit', 'unity_sprites.json')
DEST_ROOT = os.path.join(ROOT, 'unity', 'Assets')
PUBLISH_LOG = os.path.join(DEST_ROOT, 'Art', 'Kit', '.publish-manifest.json')
DATA_FILES = [
    (os.path.join(ROOT, 'art', 'kit', 'unity_sprites.json'),
     os.path.join(DEST_ROOT, 'Resources', 'unity_sprites.json')),
    # monitor font metrics: Resources.Load<TextAsset>("fonts/monitor_font_5x7")
    (os.path.join(ROOT, 'art', 'kit', 'fonts', 'monitor_font_5x7.json'),
     os.path.join(DEST_ROOT, 'Resources', 'fonts', 'monitor_font_5x7.json')),
    # palette for runtime tinting (MonitorScreenView reads Resources.Load<TextAsset>("palette"))
    (os.path.join(ROOT, 'art', 'kit', 'palette.json'),
     os.path.join(DEST_ROOT, 'Resources', 'palette.json')),
    (os.path.join(ROOT, 'unity', 'Assets', 'Content', 'desk_layout.json'),
     os.path.join(DEST_ROOT, 'Resources', 'desk_layout.json')),
]


def sha16(path: str) -> str:
    with open(path, 'rb') as fh:
        return hashlib.sha256(fh.read()).hexdigest()[:16]


def load_manifest() -> dict:
    with open(MANIFEST, 'r', encoding='utf-8') as fh:
        return json.load(fh)


def plan(manifest: dict):
    """Returns (to_copy, up_to_date, missing_source)."""
    to_copy, same, missing = [], [], []
    for sprite in manifest['sprites']:
        src = os.path.join(ROOT, sprite['source'])
        dst = os.path.join(DEST_ROOT, sprite['assetPath'][len('Assets/'):])
        if not os.path.isfile(src):
            missing.append(sprite['source'])
            continue
        if os.path.isfile(dst) and sha16(dst) == sprite['sha256_16']:
            same.append(sprite['assetPath'])
        else:
            to_copy.append((src, dst, sprite))
    return to_copy, same, missing


def write_log(published: dict) -> None:
    os.makedirs(os.path.dirname(PUBLISH_LOG), exist_ok=True)
    with open(PUBLISH_LOG, 'w', encoding='utf-8') as fh:
        json.dump({
            'note': 'generated by tools/art/publish_to_unity.py -- do not edit',
            'files': published,
        }, fh, indent=2, sort_keys=True)
        fh.write('\n')


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--verify', action='store_true')
    ap.add_argument('--prune', action='store_true')
    args = ap.parse_args()

    if not os.path.isfile(MANIFEST):
        print('FAIL: art/kit/unity_sprites.json missing -- run tools/art/make_sprite_manifest.py')
        return 1
    manifest = load_manifest()
    to_copy, same, missing = plan(manifest)

    if missing:
        for m in missing:
            print('  FAIL source missing:', m)
        return 1

    if args.verify:
        if to_copy:
            for _src, _dst, sprite in to_copy[:10]:
                print('  STALE in Unity:', sprite['assetPath'])
            print(f'FAIL: {len(to_copy)} sprite(s) out of date in unity/Assets/Art/Kit '
                  f'-- run: python tools/art/publish_to_unity.py')
            return 1
        stale_data = [os.path.relpath(dst, ROOT) for src, dst in DATA_FILES
                      if not os.path.isfile(dst) or sha16(dst) != sha16(src)]
        if stale_data:
            for d in stale_data:
                print('  STALE data file:', d)
            print('FAIL: Resources json out of date -- run: python tools/art/publish_to_unity.py')
            return 1
        print(f'PASS: unity/Assets/Art/Kit matches art/kit ({len(same)} sprites, sha256 verified)')
        print(f'      data files current: ' + ', '.join(os.path.basename(d) for _s, d in DATA_FILES))
        return 0

    for src, dst in DATA_FILES:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.isfile(dst) or sha16(dst) != sha16(src):
            shutil.copyfile(src, dst)
            print('  copied ' + os.path.relpath(dst, ROOT))

    published = {}
    for src, dst, sprite in to_copy:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        published[sprite['assetPath']] = sprite['sha256_16']
        print(f'  copied {sprite["assetPath"]}')
    for _src, dst, sprite in to_copy:
        pass

    # the log describes the whole published set, so a fresh clone verifies identically
    full = {s['assetPath']: s['sha256_16'] for s in manifest['sprites']}
    write_log(full)

    if args.prune:
        keep = {os.path.normpath(os.path.join(DEST_ROOT, a[len('Assets/'):]))
                for a in full}
        for folder in ('applicants', 'portraits', 'ui', 'icons', 'stamps', 'desk', 'backgrounds'):
            d = os.path.join(DEST_ROOT, 'Art', 'Kit', folder)
            if not os.path.isdir(d):
                continue
            for f in os.listdir(d):
                if f.endswith('.png') and os.path.normpath(os.path.join(d, f)) not in keep:
                    os.remove(os.path.join(d, f))
                    print('  pruned', os.path.relpath(os.path.join(d, f), ROOT))

    print(f'published: {len(to_copy)} copied, {len(same)} already current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
