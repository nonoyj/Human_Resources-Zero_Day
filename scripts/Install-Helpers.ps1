<#
.SYNOPSIS
    Puts the repo's helper commands somewhere you can type them from anywhere.
.DESCRIPTION
    The player kept hitting "Where-Am-I is not recognized" because a repo script only exists while you
    are standing in the repo. This copies a tiny launcher into %USERPROFILE%\bin, which is on PATH for
    the current user, so `Where-Am-I` works from any prompt afterwards.

    It does not need administrator rights, it touches nothing outside %USERPROFILE%\bin, and running it
    twice is harmless.
.EXAMPLE
    .\scripts\Install-Helpers.ps1
    .\scripts\Install-Helpers.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$home_ = if ($env:USERPROFILE) { $env:USERPROFILE } else { $HOME }
$bin = Join-Path $home_ 'bin'
$target = Join-Path $bin 'Where-Am-I.ps1'

if ($Uninstall) {
    if (Test-Path -LiteralPath $target) { Remove-Item -LiteralPath $target -Force; Write-Host "removed $target" }
    return
}

if (-not (Test-Path -LiteralPath $bin)) { New-Item -ItemType Directory -Path $bin | Out-Null }

# A launcher, not a copy: the repo stays the single source of truth, so updating the repo updates the
# command. The path is baked in at install time because that is the one thing a launcher cannot discover.
$launcher = @"
& '$repo\scripts\Where-Am-I.ps1' @args
"@
$launcher = "# generated by scripts\Install-Helpers.ps1 -- do not edit`r`n" + $launcher
[System.IO.File]::WriteAllText($target, $launcher, (New-Object System.Text.UTF8Encoding($true)))
Write-Host "installed  $target"

# %USERPROFILE%\bin is on PATH for new shells in Windows 10+; add it for this user if it is missing.
$userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
if (-not $userPath) { $userPath = '' }      # a profile with no user PATH yet is common on fresh Windows
if (($userPath -split ';') -notcontains $bin) {
    [Environment]::SetEnvironmentVariable('Path', ($userPath.TrimEnd(';') + ';' + $bin), 'User')
    Write-Host "added $bin to your user PATH (open a NEW PowerShell window for it to take effect)"
} else {
    Write-Host "$bin is already on your PATH"
}

Write-Host ""
Write-Host "  Then, from any folder:" -ForegroundColor White
Write-Host "      Where-Am-I"
