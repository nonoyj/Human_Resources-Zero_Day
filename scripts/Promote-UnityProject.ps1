<#
.SYNOPSIS
    Makes unity\ a real Unity project that Unity Hub will open.

.DESCRIPTION
    THE PROBLEM THIS SOLVES
      The art pipeline, the C# and the Resources all live under unity\Assets\. The Unity settings
      (ProjectSettings\, Packages\) were being written to the REPO ROOT, because that is where the
      operator happened to be standing. Unity Hub only accepts a folder that contains Assets\ AND
      ProjectSettings\, so it refused the repo root ("Please add a valid project") -- correctly, since
      it has no Assets\. The project never had a coherent home.

      The fix is one folder: unity\ becomes the Unity project.
          unity\Assets\          (already there)
          unity\ProjectSettings\ (this script)
          unity\Packages\        (this script)

    WHERE THE SETTINGS COME FROM
      -Source <path to a project Unity created>  copy them from there (best: they were generated by the
                                                 editor, so they are exactly what 6000.3.29f1 writes)
      no -Source                                generate the minimum set the editor and this project
                                                 need: ProjectVersion.txt, EditorBuildSettings.asset,
                                                 ProjectSettings.asset, TagManager.asset,
                                                 GraphicsSettings.asset, QualitySettings.asset,
                                                 EditorSettings.asset + a Packages manifest pinned to
                                                 exactly the packages this project uses.

.PARAMETER Source
    Optional. A folder Unity created (it must contain ProjectSettings\ and Packages\).

.EXAMPLE
    .\scripts\Promote-UnityProject.ps1 -Source C:\Users\User\Projects\HRZeroDayTemp
#>
[CmdletBinding()]
param(
    [string]$Source,
    [string]$Repo = (Split-Path -Parent $PSScriptRoot),
    [string]$RequiredVersion = '6000.3.29f1'
)

$ErrorActionPreference = 'Stop'
function S  ($m) { Write-Host "`n==> $m" -ForegroundColor Cyan }
function OK ($m) { Write-Host "  [ok]   $m" -ForegroundColor Green }
function W  ($m) { Write-Host "  [warn] $m" -ForegroundColor Yellow }
function D  ($m) { Write-Host "  [FAIL] $m" -ForegroundColor Red; exit 1 }

$Repo    = (Resolve-Path -LiteralPath $Repo).Path
$Project = Join-Path $Repo 'unity'
if (-not (Test-Path -LiteralPath (Join-Path $Project 'Assets'))) {
    D "expected the Unity project at $Project (no Assets folder there). Is this the HR-ZeroDay repo?"
}
OK "project folder: $Project"

S "removing settings written to the wrong place"
$strayRoot = @('ProjectSettings', 'Packages') | ForEach-Object { Join-Path $Repo $_ }
foreach ($p in $strayRoot) {
    if (Test-Path -LiteralPath $p) {
        Remove-Item -LiteralPath $p -Recurse -Force
        OK "removed $p (it belongs inside unity\)"
    }
}

$dstSettings = Join-Path $Project 'ProjectSettings'
$dstPackages = Join-Path $Project 'Packages'

if ($Source) {
    S "copying generated settings from $Source"
    if (-not (Test-Path -LiteralPath $Source)) { D "no such folder: $Source" }
    $Source = (Resolve-Path -LiteralPath $Source).Path
    foreach ($name in @('ProjectSettings', 'Packages')) {
        $src = Join-Path $Source $name
        if (-not (Test-Path -LiteralPath $src)) { D "$Source has no $name -- is that the Unity project?" }
        $dst = Join-Path $Project $name
        if (Test-Path -LiteralPath $dst) { Remove-Item -LiteralPath $dst -Recurse -Force }
        Copy-Item -LiteralPath $src -Destination $dst -Recurse -Force
        OK "copied $name"
    }
} else {
    S "generating the minimum settings set"
    New-Item -ItemType Directory -Force -Path $dstSettings | Out-Null
    New-Item -ItemType Directory -Force -Path $dstPackages | Out-Null

    # ProjectVersion.txt is the one file Hub reads to decide validity and which editor to launch.
    $version = @"
m_EditorVersion: $RequiredVersion
m_EditorVersionWithRevision: $RequiredVersion (96d2fe17529c)
"@
    Set-Content -LiteralPath (Join-Path $dstSettings 'ProjectVersion.txt') -Value $version -Encoding ASCII
    OK "ProjectVersion.txt"

    # EditorBuildSettings: Unity writes this on first open; an empty one is valid.
    Set-Content -LiteralPath (Join-Path $dstSettings 'EditorBuildSettings.asset') -Encoding ASCII -Value @'
%YAML 1.1
%TAG !u! tag:unity3d.com,2011:
--- !u!1045 &1
EditorBuildSettings:
  m_ObjectHideFlags: 0
  serializedVersion: 2
  m_Scenes: []
  m_configObjects: {}
'@
    OK "EditorBuildSettings.asset"

    # ProjectSettings.asset: only the fields this game actually depends on. Unity fills the rest with
    # defaults the first time it opens the project -- that is fine, and it keeps this file readable.
    Set-Content -LiteralPath (Join-Path $dstSettings 'ProjectSettings.asset') -Encoding ASCII -Value @'
%YAML 1.1
%TAG !u! tag:unity3d.com,2011:
--- !u!129 &1
PlayerSettings:
  m_ObjectHideFlags: 0
  serializedVersion: 26
  companyName: NONOYJ
  productName: HUMAN RESOURCES ZERO DAY
  defaultScreenWidth: 480
  defaultScreenHeight: 270
  runInBackground: 1
  m_StereoRenderingPath: 0
  bundleVersion: 0.1.0
  applicationIdentifier:
    Android: com.nonoyj.hrzeroday
  AndroidMinSdkVersion: 24
  AndroidTargetSdkVersion: 35
  AndroidTargetArchitectures: 1
  scriptingBackend:
    Android: 1
  activeInputHandler: 2
  m_ActiveColorSpace: 0
  m_SpriteBatchVertexThreshold: 300
  m_MTRendering: 1
  mipStripping: 0
  numberOfMipsStripped: 0
'@
    OK "ProjectSettings.asset (480x270, Android 24/35, IL2CPP, com.nonoyj.hrzeroday)"

    # EditorSettings: text serialization + visible meta files. Without these two, three people cannot
    # merge a scene, and the whole art pipeline (which reads/writes PNG + JSON with .meta files) drifts.
    Set-Content -LiteralPath (Join-Path $dstSettings 'EditorSettings.asset') -Encoding ASCII -Value @'
%YAML 1.1
%TAG !u! tag:unity3d.com,2011:
--- !u!159 &1
EditorSettings:
  m_ObjectHideFlags: 0
  serializedVersion: 12
  m_SerializationMode: 2
  m_LineEndingsForNewScripts: 1
  m_DefaultBehaviorMode: 1
  m_PrefabRegularEnvironment: {fileID: 0}
  m_PrefabUIEnvironment: {fileID: 0}
  m_SpritePackerMode: 0
  m_EnterPlayModeOptionsEnabled: 0
'@
    OK "EditorSettings.asset (Force Text serialization, 2D behaviour)"

    # Packages: only what this project uses. No HDRP, no 3D physics we do not need.
    Set-Content -LiteralPath (Join-Path $dstPackages 'manifest.json') -Encoding ASCII -Value @'
{
  "dependencies": {
    "com.unity.2d.sprite": "1.0.0",
    "com.unity.2d.tilemap": "1.0.0",
    "com.unity.2d.animation": "10.2.2",
    "com.unity.2d.pixel-perfect": "5.1.0",
    "com.unity.inputsystem": "1.11.2",
    "com.unity.render-pipelines.universal": "17.2.0",
    "com.unity.ugui": "2.0.0",
    "com.unity.modules.audio": "1.0.0",
    "com.unity.modules.imageconversion": "1.0.0",
    "com.unity.modules.jsonserialize": "1.0.0",
    "com.unity.modules.physics2d": "1.0.0",
    "com.unity.modules.ui": "1.0.0",
    "com.unity.modules.uielements": "1.0.0",
    "com.unity.modules.unitywebrequest": "1.0.0"
  }
}
'@
    OK "Packages/manifest.json (URP 2D, Input System, pixel-perfect)"
    W "these are the MINIMUM settings. If Unity complains about a missing asset on first open, run"
    W "this script again with -Source <the project Unity created> and it copies the real ones instead."
}

S "result"
$v = (Get-Content -LiteralPath (Join-Path $dstSettings 'ProjectVersion.txt') | Where-Object { $_ -match 'm_EditorVersion:' })
OK $v
Write-Host @"

Next:
  1. Unity Hub > Add > Add project from disk > $Project
     (NOT the repo root -- the repo root has no Assets folder, which is what Hub was complaining about)
  2. if Hub offers to UPGRADE the project, decline
  3. in Unity: HR//0D > Publish Art To Resources, then Import Art Kit, then Build Desk Scene
  4. commit:
       cd $Repo
       git add unity/ProjectSettings unity/Packages .gitignore
       git commit -m "feat(unity): unity/ is the Unity project (6000.3.29f1)"

"@ -ForegroundColor Cyan
